"""Two isolated browser sessions; run against a fresh demo output on port 8765."""
from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser = p.chromium.launch(channel="chrome", headless=True)
    ctx_a, ctx_b = browser.new_context(), browser.new_context()
    a, b = ctx_a.new_page(), ctx_b.new_page()
    errors = []
    for page in (a, b):
        page.on("pageerror", lambda error: errors.append(str(error)))
        page.goto("http://127.0.0.1:8765")
        page.wait_for_load_state("networkidle")
    b.locator("#jump").fill("3")
    b.locator("#jump-go").click()
    a.locator('[data-review-field="reason"]').fill("A独立保存")
    b.locator("#error-detail").fill("B独立保存")
    expect(a.locator("#save-state")).to_contain_text("已保存")
    expect(b.locator("#save-state")).to_contain_text("已保存")
    expect(a.locator("#stats")).to_contain_text("2 条草稿", timeout=10000)
    expect(b.locator("#conflict")).to_be_hidden()
    # Both edit the same record; pause B's writes to preserve its draft.
    b.locator("#jump").fill("1")
    b.locator("#jump-go").click()
    expect(b.locator('[data-review-field="reason"]')).to_have_value("A独立保存")
    b.route("**/api/save", lambda route: route.abort())
    b.locator('[data-review-field="reason"]').fill("B未保存草稿")
    a.locator('[data-review-field="reason"]').fill("A最新版本")
    expect(a.locator("#save-state")).to_contain_text("已保存")
    expect(b.locator("#conflict")).to_be_visible(timeout=10000)
    expect(b.locator('[data-review-field="reason"]')).to_have_value("B未保存草稿")
    expect(b.locator("#remote-annotation")).to_contain_text("A最新版本")
    b.reload()
    expect(b.locator("#conflict")).to_be_visible()
    expect(b.locator('[data-review-field="reason"]')).to_have_value("B未保存草稿")
    b.unroute("**/api/save")
    b.on("dialog", lambda dialog: dialog.accept())
    b.locator("#use-draft").click()
    expect(b.locator("#save-state")).to_contain_text("已保存")
    expect(b.locator("#conflict")).to_be_hidden()
    a.locator("h1").click()
    expect(a.locator('[data-review-field="reason"]')).to_have_value("B未保存草稿", timeout=10000)
    # When focused, remote updates wait; first local edit detects conflict.
    a.locator('[data-review-field="reason"]').focus()
    b.locator('[data-review-field="reason"]').fill("B更新服务端")
    expect(b.locator("#save-state")).to_contain_text("已保存")
    expect(a.locator("#notice")).to_contain_text("当前记录已有更新", timeout=10000)
    expect(a.locator('[data-review-field="reason"]')).to_have_value("B未保存草稿")
    a.locator('[data-review-field="reason"]').fill("A继续编辑保留")
    expect(a.locator("#conflict")).to_be_visible()
    a.on("dialog", lambda dialog: dialog.accept())
    a.locator("#use-remote").click()
    expect(a.locator('[data-review-field="reason"]')).to_have_value("B更新服务端")
    expect(a.locator("#conflict")).to_be_hidden()
    assert not errors, errors
    print("Two-user browser test passed: independent writes, polling, focused input, conflict, draft restore, both resolutions.")
    browser.close()
